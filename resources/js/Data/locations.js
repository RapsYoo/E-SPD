/**
 * Daftar kota keberangkatan populer di Indonesia (dengan Jakarta di urutan teratas)
 */
export const DEPARTURE_OPTIONS = (() => {
  const priority = [
    { value: 'Jakarta', label: 'Jakarta', sublabel: 'DKI Jakarta' },
    { value: 'Kota Bogor, Jawa Barat', label: 'Kota Bogor', sublabel: 'Jawa Barat' },
    { value: 'Kota Depok, Jawa Barat', label: 'Kota Depok', sublabel: 'Jawa Barat' },
    { value: 'Kota Tangerang Selatan, Banten', label: 'Kota Tangerang Selatan', sublabel: 'Banten' },
    { value: 'Kota Tangerang, Banten', label: 'Kota Tangerang', sublabel: 'Banten' },
    { value: 'Kota Bekasi, Jawa Barat', label: 'Kota Bekasi', sublabel: 'Jawa Barat' },
    { value: 'Kota Bandung, Jawa Barat', label: 'Kota Bandung', sublabel: 'Jawa Barat' },
  ];
  const seen = new Set(priority.map((item) => item.value));
  const rest = [];

  Object.entries(INDONESIA_LOCATIONS).forEach(([provinsi, cities]) => {
    cities.forEach((kota) => {
      const fullValue = kota === 'Jakarta' ? 'Jakarta' : `${kota}, ${provinsi}`;
      if (!seen.has(fullValue)) {
        seen.add(fullValue);
        rest.push({
          value: fullValue,
          label: kota,
          sublabel: provinsi,
        });
      }
    });
  });

  return [...priority, ...rest];
})();

/**
 * Ambil daftar provinsi/wilayah berdasarkan kategori & negara
 */
export function getProvinceOptions(kategoriPerjalanan, negara) {
  if (kategoriPerjalanan !== 'LUAR_NEGERI' || negara === 'Indonesia') {
    return INDONESIA_PROVINCES.map((prov) => ({
      value: prov,
      label: prov,
      sublabel: 'Provinsi di Indonesia',
    }));
  }

  if (!negara) {
    // Jika negara belum dipilih pada LUAR_NEGERI, tampilkan semua wilayah dengan sublabel negaranya
    const allRegions = [];
    Object.entries(WORLD_LOCATIONS).forEach(([countryName, regionsObj]) => {
      Object.keys(regionsObj).forEach((regionName) => {
        allRegions.push({
          value: regionName,
          label: regionName,
          sublabel: countryName,
          country: countryName,
        });
      });
    });
    return allRegions;
  }

  const countryRegions = WORLD_LOCATIONS[negara];
  if (!countryRegions) {
    return [];
  }

  return Object.keys(countryRegions).map((regionName) => ({
    value: regionName,
    label: regionName,
    sublabel: negara,
    country: negara,
  }));
}

/**
 * Ambil daftar kota berdasarkan kategori, negara, dan provinsi/wilayah
 */
export function getCityOptions(kategoriPerjalanan, negara, provinsi) {
  if (kategoriPerjalanan !== 'LUAR_NEGERI' || negara === 'Indonesia') {
    if (provinsi && INDONESIA_LOCATIONS[provinsi]) {
      return INDONESIA_LOCATIONS[provinsi].map((kota) => ({
        value: kota,
        label: kota,
        sublabel: provinsi,
        province: provinsi,
        country: 'Indonesia',
      }));
    }

    // Jika provinsi belum dipilih, tampilkan semua kota di Indonesia beserta sublabel provinsinya
    const allCities = [];
    Object.entries(INDONESIA_LOCATIONS).forEach(([provName, cities]) => {
      cities.forEach((kota) => {
        allCities.push({
          value: kota,
          label: kota,
          sublabel: provName,
          province: provName,
          country: 'Indonesia',
        });
      });
    });
    return allCities;
  }

  // LUAR_NEGERI
  if (negara && WORLD_LOCATIONS[negara]) {
    const regionsObj = WORLD_LOCATIONS[negara];
    if (provinsi && regionsObj[provinsi]) {
      return regionsObj[provinsi].map((kota) => ({
        value: kota,
        label: kota,
        sublabel: `${provinsi}, ${negara}`,
        province: provinsi,
        country: negara,
      }));
    }

    const countryCities = [];
    Object.entries(regionsObj).forEach(([regionName, cities]) => {
      cities.forEach((kota) => {
        countryCities.push({
          value: kota,
          label: kota,
          sublabel: `${regionName}, ${negara}`,
          province: regionName,
          country: negara,
        });
      });
    });
    return countryCities;
  }

  // Jika negara luar negeri belum dipilih, tampilkan semua kota luar negeri beserta wilayah & negaranya
  const globalCities = [];
  Object.entries(WORLD_LOCATIONS).forEach(([countryName, regionsObj]) => {
    Object.entries(regionsObj).forEach(([regionName, cities]) => {
      cities.forEach((kota) => {
        globalCities.push({
          value: kota,
          label: kota,
          sublabel: `${regionName}, ${countryName}`,
          province: regionName,
          country: countryName,
        });
      });
    });
  });
  return globalCities;
}

/**
 * Mengurai string `tempat_tujuan` dan `negara_tujuan` dari database/draft menjadi { negara, provinsi, kota }
 */
export function parseDestination(kategoriPerjalanan, tempatTujuan = '', negaraTujuan = '') {
  const isLuarNegeri = kategoriPerjalanan === 'LUAR_NEGERI';
  const rawTempat = (tempatTujuan || '').trim();
  const rawNegara = (negaraTujuan || '').trim();

  if (!isLuarNegeri) {
    if (!rawTempat) {
      return { negara: 'Indonesia', provinsi: '', kota: '' };
    }

    // Format umum: "Kota Bandung, Jawa Barat"
    const parts = rawTempat.split(',').map((s) => s.trim()).filter(Boolean);
    if (parts.length >= 2) {
      const possibleProvince = parts[parts.length - 1];
      const possibleCity = parts.slice(0, -1).join(', ');
      if (INDONESIA_LOCATIONS[possibleProvince]) {
        return { negara: 'Indonesia', provinsi: possibleProvince, kota: possibleCity };
      }
    }

    // Cek apakah rawTempat cocok dengan salah satu kota di Indonesia
    for (const [provName, cities] of Object.entries(INDONESIA_LOCATIONS)) {
      const matchedCity = cities.find((c) => c.toLowerCase() === rawTempat.toLowerCase());
      if (matchedCity) {
        return { negara: 'Indonesia', provinsi: provName, kota: matchedCity };
      }
    }

    // Cek apakah rawTempat adalah nama provinsi
    const matchedProv = INDONESIA_PROVINCES.find((p) => p.toLowerCase() === rawTempat.toLowerCase());
    if (matchedProv) {
      return { negara: 'Indonesia', provinsi: matchedProv, kota: '' };
    }

    return {
      negara: 'Indonesia',
      provinsi: parts[1] || '',
      kota: parts[0] || rawTempat,
    };
  }

  // LUAR_NEGERI
  let negara = rawNegara;
  let provinsi = '';
  let kota = '';

  const parts = rawTempat.split(',').map((s) => s.trim()).filter(Boolean);
  if (parts.length >= 2) {
    kota = parts[0];
    provinsi = parts.slice(1).join(', ');
  } else if (parts.length === 1) {
    kota = parts[0];
  }

  // Jika negara cocok di WORLD_LOCATIONS dan provinsi belum terisi, cari wilayah dari nama kota
  if (negara && WORLD_LOCATIONS[negara] && kota && !provinsi) {
    for (const [regionName, cities] of Object.entries(WORLD_LOCATIONS[negara])) {
      const matched = cities.find((c) => c.toLowerCase() === kota.toLowerCase());
      if (matched) {
        kota = matched;
        provinsi = regionName;
        break;
      }
    }
  }

  return { negara, provinsi, kota };
}

/**
 * Menggabungkan kota & provinsi/wilayah menjadi string `tempat_tujuan`
 */
export function formatTempatTujuan(kota = '', provinsi = '') {
  const cleanKota = (kota || '').trim();
  const cleanProv = (provinsi || '').trim();

  if (cleanKota && cleanProv) {
    if (cleanKota.toLowerCase().includes(cleanProv.toLowerCase())) {
      return cleanKota;
    }
    return `${cleanKota}, ${cleanProv}`;
  }

  return cleanKota || cleanProv || '';
}

